    def new_file(self):
        srs_mesh = None
        path = ""
        if self.lay_mesh:
            srs_mesh = self.lay_mesh.crs()
        dlg = dlg_create_shapefile(self.tr("culvert"), srs_mesh, self)
        dlg.setWindowModality(Qt.WindowModality.WindowModal)
        if dlg.exec():
            path, crs = dlg.cur_shp, dlg.cur_crs
        if path:
            self.create_new_shp(path, crs)

    def create_new_shp(self, path, crs):
        layerFields = QgsFields()
        for fld in self.culv_flds:
            layerFields.append(QgsField(fld[0], fld[1]))

        tmp_lay = QgsVectorLayer(f"MultiLineString?crs={crs.authid()}", "", "memory")
        pr = tmp_lay.dataProvider()
        pr.addAttributes(layerFields)
        tmp_lay.updateFields()

        layerDriver = GdalUtils.getVectorDriverFromFileName(path)

        options = QgsVectorFileWriter.SaveVectorOptions()
        options.driverName = layerDriver
        options.fileEncoding = "utf-8"
        result = QgsVectorFileWriter.writeAsVectorFormatV2(
            layer=tmp_lay,
            fileName=path,
            transformContext=QgsCoordinateTransformContext(),
            options=options,
        )
        if result[0] != Qgis.VectorExportResult.Success:
            self.writeError(self.tr("Error during culvert file creation : {}").format(result[1]))
            return

        shp_lay = QgsVectorLayer(path, os.path.basename(path).rsplit(".", 1)[0], "ogr")
        shp_lay.setCrs(crs)
        shp_lay.loadNamedStyle(self.file_culv_style)
        shp_lay.saveDefaultStyle()
        self.project.addMapLayer(shp_lay)
        self.cb_lay_culv.setCurrentIndex(self.cb_lay_culv.findData(shp_lay.id(), 32))

    def culv_lay_changed(self, *_):
        self.disconnect_culv_layer()

        lay_id = self.cb_lay_culv.currentData(32)
        self.cur_culv_id = None
        if lay_id:
            self.lay_culv = self.project.mapLayer(lay_id)
            self.lay_culv.selectionChanged.connect(self.cur_culv_changed)
            self.lay_culv.editingStarted.connect(self.cur_culv_changed)
            self.lay_culv.editingStopped.connect(self.cur_culv_changed)
            self.lay_culv.crsChanged.connect(self.culv_crs_changed)
            self.update_transforms()

            # Nothing to update in a new empty layer
            if self.culv_to_mesh is not None and self.is_opening is False and self.lay_culv.featureCount() > 0:
                self.update_all_n()
                if (
                    QMessageBox.question(
                        self,
                        self.tr("Automatic Z Update"),
                        self.tr(
                            "Culvert layer has been changed.\n"
                            "Update culvert features with Automatic Z checked ?"
                        ),
                        QMessageBox.StandardButton.Cancel | QMessageBox.StandardButton.Ok,
                    )
                    == QMessageBox.StandardButton.Ok
                ):
                    self.update_all_auto_z()
        else:
            self.lay_culv = None
            self.update_transforms()
        self.valid_mesh_culv()

    def culv_crs_changed(self):
        self.update_transforms()
        self.valid_mesh_culv()
        if self.culv_to_mesh is not None:
            self.update_all_n()

    def cur_culv_changed(self):
        if self.lay_culv:
            if self.lay_culv.selectedFeatureCount() == 1:
                self.cur_culv_id = self.lay_culv.selectedFeatureIds()[0]
            else:
                self.cur_culv_id = None
        else:
            self.cur_culv_id = None
        self.display_culv_info()

    def display_culv_info(self):
        if self.lay_culv:
            if self.cur_culv_id is None:
                if self.lay_culv.selectedFeatureCount() == 0:
                    self.gb_cur_culv.setTitle(self.tr("No culvert selected"))
                else:
                    self.gb_cur_culv.setTitle(self.tr("More than one culvert selected"))
                self.clear_info()
                self.gb_cur_culv.setEnabled(False)
            else:
                self.gb_cur_culv.setTitle(self.tr("Selected culvert informations"))
                self.fill_info()
                self.gb_cur_culv.setEnabled(not self.lay_culv.isEditable())
        else:
            self.gb_cur_culv.setTitle(self.tr("No culvert layer selected"))
            self.clear_info()
            self.gb_cur_culv.setEnabled(False)

    def clear_info(self):
        self.ctrl_signal_blocked = True
        for fld in self.culv_flds:
            ctrl = fld[2]
            if ctrl:
                if isinstance(ctrl, QDoubleSpinBox):
                    ctrl.setValue(0.0)
                elif isinstance(ctrl, QSpinBox):
                    ctrl.setValue(1)
                elif isinstance(ctrl, QComboBox):
                    ctrl.setCurrentIndex(0)
                elif isinstance(ctrl, QCheckBox):
                    ctrl.setCheckState(Qt.CheckState.Unchecked)
                elif isinstance(ctrl, QLineEdit):
                    ctrl.setText("")
        self.ctrl_signal_blocked = False

    def fill_info(self):
        self.ctrl_signal_blocked = True
        ft = self.lay_culv.getFeature(self.cur_culv_id)
        for fld in self.culv_flds:
            if fld[2]:
                self.display_info(fld[2], ft[fld[0]])
        self.ctrl_signal_blocked = False

    def display_info(self, ctrl, val):
        if isinstance(ctrl, QDoubleSpinBox):
            if is_null(val):
                ctrl.setValue(0.0)
            else:
                ctrl.setValue(val)
        elif isinstance(ctrl, QSpinBox):
            if is_null(val):
                ctrl.setValue(1)
            else:
                ctrl.setValue(val)
        elif isinstance(ctrl, QComboBox):
            idx = to_integer(val)
            if idx is None:
                ctrl.setCurrentIndex(0)
            else:
                ctrl.setCurrentIndex(idx)
        elif isinstance(ctrl, QCheckBox):
            if not is_null(val) and val == 1:
                ctrl.setCheckState(Qt.CheckState.Checked)
            else:
                ctrl.setCheckState(Qt.CheckState.Unchecked)
        elif isinstance(ctrl, QLineEdit):
            ctrl.setText("" if is_null(val) else str(val))

    def write_attributes(self, attrs):
        """Write {feature id: {field index: value}} without ever committing the user's own edits."""
        if self.lay_culv.isEditable():
            for fid, values in attrs.items():
                for idx, value in values.items():
                    self.lay_culv.changeAttributeValue(fid, idx, value)
        else:
            self.lay_culv.dataProvider().changeAttributeValues(attrs)
            self.lay_culv.triggerRepaint()

    def field_index(self, name):
        return self.lay_culv.fields().lookupField(name)

    def ctrl_edited(self):
        ft = None
        if not self.ctrl_signal_blocked:
            if self.cur_culv_id is not None:
                ft = self.lay_culv.getFeature(self.cur_culv_id)

                ctrl = self.sender()
                if isinstance(ctrl, QDoubleSpinBox) or isinstance(ctrl, QSpinBox):
                    val = ctrl.value()
                elif isinstance(ctrl, QComboBox):
                    val = ctrl.currentIndex()
                elif isinstance(ctrl, QCheckBox):
                    if ctrl.checkState() == Qt.CheckState.Checked:
                        val = 1
                    else:
                        val = 0
                elif isinstance(ctrl, QLineEdit):
                    val = ctrl.text()

                field_idx = None
                for idx in range(len(self.culv_flds)):
                    if ctrl == self.culv_flds[idx][2]:
                        field_name = self.culv_flds[idx][0]
                        field_idx = self.field_index(field_name)
                        break

                if field_idx is not None:
                    self.write_attributes({self.cur_culv_id: {field_idx: val}})

        if self.sender() == self.cb_auto_z:
            self.sb_z1.setEnabled(not self.cb_auto_z.isChecked())
            self.sb_z2.setEnabled(not self.cb_auto_z.isChecked())
            if ft:
                if not self.mesh_ready():
                    self.writeError(self.tr("Error on Z calculation : {}").format(self.tr("No valid mesh dataset.")))
                    return

                (n1, n2), err = self.nodes_of_feature(ft)

                if err is not None:
                    self.writeError(self.tr("Error on Z calculation : {}").format(err))
                    return

                attrs = {self.cur_culv_id: {self.field_index("N1"): n1, self.field_index("N2"): n2}}

                if self.cb_auto_z.isChecked():
                    z1 = MeshUtils.zFromN(self.lay_mesh, self.mesh_dataset_index(), n1)
                    z2 = MeshUtils.zFromN(self.lay_mesh, self.mesh_dataset_index(), n2)

                    self.sb_z1.setValue(z1)
                    self.sb_z2.setValue(z2)

                self.write_attributes(attrs)

        if self.sender() == self.cb_auto_a:
            self.sb_a1.setEnabled(not self.cb_auto_a.isChecked())
            self.sb_a2.setEnabled(not self.cb_auto_a.isChecked())
            if ft and (self.cb_auto_a.isChecked()):
                a1, a2 = calculangle(ft)
                self.sb_a1.setValue(a1)
                self.sb_a2.setValue(a2)

        if self.sender() == self.cb_auto_l:
            self.sb_length.setEnabled(not self.cb_auto_l.isChecked())
            if ft and (self.cb_auto_l.isChecked()):
                self.sb_length.setValue(ft.geometry().length())

        if self.sender() == self.cb_circ:
            self.sb_larg.setEnabled(not self.cb_circ.isChecked())
            if ft and (self.cb_circ.isChecked()):
                self.sb_larg.setValue(self.sb_haut1.value())
                self.sb_haut2.setValue(self.sb_haut1.value())
        if self.sender() == self.sb_haut1 and self.cb_circ.isChecked():
            self.sb_larg.setValue(self.sb_haut1.value())
            self.sb_haut2.setValue(self.sb_haut1.value())

    def reset_val(self):
        for fld in self.culv_flds:
            ctrl = fld[2]
            if ctrl:
                if isinstance(ctrl, QDoubleSpinBox):
                    if ctrl in [self.sb_ce1, self.sb_ce2]:
                        ctrl.setValue(0.5)
                    elif ctrl in [self.sb_cs1, self.sb_cs2, self.sb_l12]:
                        ctrl.setValue(1.0)
                    else:
                        ctrl.setValue(0.0)
                elif isinstance(ctrl, QSpinBox):
                    ctrl.setValue(1)
                elif isinstance(ctrl, QComboBox):
                    ctrl.setCurrentIndex(0)
                elif isinstance(ctrl, QCheckBox):
                    ctrl.setCheckState(Qt.CheckState.Unchecked)

    def nodes_of_feature(self, ft):
        """((N1, N2), error) of the extremities of a culvert."""
        vertices = MeshUtils.lineVertices(ft.geometry())
        if len(vertices) < 2 or self.locator is None or self.culv_to_mesh is None:
            return (None, None), self.tr("The culvert geometry is not valid.")

        nodes = []
        error = None
        for vertex in (vertices[0], vertices[-1]):
            try:
                node, err = self.locator.nearest_node(self.culv_to_mesh.transform(vertex))
            except QgsCsException:
                node, err = None, self.tr("The coordinates cannot be converted to the CRS of the mesh.")
            if err is not None:
                error = err
            nodes.append(node)
        return tuple(nodes), error

    def mesh_dataset_index(self):
        return QgsMeshDatasetIndex(self.cur_mesh_dataset, self.cur_mesh_time)

    def mesh_ready(self):
        """True if the node lookup and the dataset used for Z are available."""
        return (
            self.lay_mesh is not None
            and self.locator is not None
            and self.cur_mesh_dataset is not None
            and self.cur_mesh_time is not None
        )

    def update_all_n(self, log=True):
        if self.lay_mesh is None or self.locator is None or self.culv_to_mesh is None:
            return

        attrs = dict()
        success = True
        for ft in self.lay_culv.getFeatures():
            (n1, n2), err = self.nodes_of_feature(ft)

            if err is not None:
                success = False
                n1 = NULL
                n2 = NULL
                if log:
                    self.writeError(self.tr("Error on N calculation : {}").format(err))

            attrs[ft.id()] = {self.field_index("N1"): n1, self.field_index("N2"): n2}

        self.write_attributes(attrs)
        if log and success:
            self.writeSuccess(self.tr("N values updated"))

    def update_all_auto_z(self):
        if not self.mesh_ready():
            self.writeError(self.tr("Error on Z calculation : {}").format(self.tr("No valid mesh dataset.")))
            return

        attrs = dict()
        success = True
        for ft in self.lay_culv.getFeatures():
            if ft["AZ"] != 1:
                continue

            (n1, n2), err = self.nodes_of_feature(ft)
            if err is None:
                z1 = MeshUtils.zFromN(self.lay_mesh, self.mesh_dataset_index(), n1)
                z2 = MeshUtils.zFromN(self.lay_mesh, self.mesh_dataset_index(), n2)
                attrs[ft.id()] = {self.field_index("Z1"): z1, self.field_index("Z2"): z2}
            else:
                success = False
                self.writeError(self.tr("Error on Z calculation : {}").format(err))

        self.write_attributes(attrs)
        if success:
            self.writeSuccess(self.tr("Z values updated"))
        self.display_culv_info()

