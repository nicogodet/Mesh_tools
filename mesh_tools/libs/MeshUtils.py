import functools
import math

from typing import Optional

from qgis.core import (
    QgsCoordinateTransform,
    QgsCsException,
    QgsFeature,
    QgsGeometry,
    QgsLineString,
    QgsMesh,
    QgsMeshDatasetGroupMetadata,
    QgsMeshDatasetIndex,
    QgsMeshLayer,
    QgsPointXY,
    QgsSpatialIndex,
    QgsTriangle,
)
from qgis.PyQt.QtCore import QCoreApplication, Qt
from qgis.PyQt.QtWidgets import QApplication


class MeshUtils:
    @staticmethod
    def findVerticesInGeometry(
        nativeMesh: QgsMesh, vertexSpatialIndex: QgsSpatialIndex, xform: QgsCoordinateTransform, geometry: QgsGeometry
    ):
        vertices = []
        vertexIds = vertexSpatialIndex.intersects(geometry.boundingBox())
        for vertexId in vertexIds:
            point = xform.transform(QgsPointXY(nativeMesh.vertex(vertexId)))
            if geometry.contains(point):
                vertices.append(point)
        return vertices

    @staticmethod
    def lineVertices(geometry: QgsGeometry) -> list:
        """Vertices of a LineString or MultiLineString, in order."""
        if geometry is None or geometry.isNull():
            return []
        return [QgsPointXY(vertex) for vertex in geometry.vertices()]

    @staticmethod
    def isScalarOnVertices(metadata: QgsMeshDatasetGroupMetadata) -> bool:
        return metadata.isScalar() and metadata.dataType() == QgsMeshDatasetGroupMetadata.DataType.DataOnVertices

    @staticmethod
    def zFromN(mesh: QgsMeshLayer, meshDatasetIndex: QgsMeshDatasetIndex, n: int):
        """Value of a scalar dataset at node n rounded to 0.01, None if there is no value."""
        value = mesh.dataProvider().datasetValue(meshDatasetIndex, n - 1).scalar()
        if not math.isfinite(value):
            return None

        return round(value, 2)

    @staticmethod
    def xyFromN(nativeMesh: QgsMesh, n: int, xform: Optional[QgsCoordinateTransform] = None):
        """Point of the node n, transformed with xform (mesh CRS to another CRS) if given."""
        error = None
        point = None

        if n < 1:
            error = MeshUtils.tr("N should a strict positive integer.")
            return point, error

        if n > nativeMesh.vertexCount():
            error = MeshUtils.tr("N is greater than the number of mesh vertices.")
            return point, error

        point = QgsPointXY(nativeMesh.vertex(n - 1))

        if xform is not None:
            try:
                point = xform.transform(point)
            except QgsCsException:
                point = None
                error = MeshUtils.tr("The node coordinates cannot be converted to the CRS of the layer.")

        return point, error

    @staticmethod
    def createVerticesSpatialIndex(nativeMesh: QgsMesh, xform: Optional[QgsCoordinateTransform] = None):
        spindex = QgsSpatialIndex()

        count = nativeMesh.vertexCount()
        offset = 0
        batch_size = 10000
        while offset < count:
            lst_ft = list()
            iterations = min(batch_size, count - offset)
            for i in range(iterations):
                ft = QgsFeature()
                vertex = QgsPointXY(nativeMesh.vertex(offset + i))
                if xform is not None:
                    vertex = xform.transform(vertex)
                ft.setGeometry(QgsGeometry.fromPointXY(vertex))
                ft.setId(offset + i)
                lst_ft.append(ft)
            spindex.addFeatures(lst_ft)
            offset += iterations

        return spindex

    @staticmethod
    def faceToTriangle(nativeMesh: QgsMesh, faceIdx: int):
        face = nativeMesh.face(faceIdx)
        points = [nativeMesh.vertex(v) for v in face]
        triangle = QgsTriangle()
        triangle.setExteriorRing(QgsLineString(points))
        return triangle

    @staticmethod
    def computeNeighbors(nativeMesh: QgsMesh) -> dict:
        dico = {}
        for faceId in range(nativeMesh.faceCount()):
            verticies = nativeMesh.face(faceId)
            for vertex in verticies:
                neighbors = list(verticies)
                neighbors.remove(vertex)
                if vertex in dico.keys():
                    for neighbor in neighbors:
                        if neighbor not in dico[vertex]:
                            dico[vertex].append(neighbor)
                else:
                    dico[vertex] = neighbors
        return dico

    @classmethod
    def tr(cls, message, context=""):
        if context == "":
            context = cls.__name__
        return QCoreApplication.translate(context, message)


def showWaitCursor(func):
    @functools.wraps(func)
    def wrapped(*args, **kwargs):
        QApplication.setOverrideCursor(Qt.CursorShape.WaitCursor)
        try:
            return func(*args, **kwargs)
        finally:
            QApplication.restoreOverrideCursor()

    return wrapped
